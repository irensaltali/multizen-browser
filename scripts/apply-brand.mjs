import { readFileSync, writeFileSync } from 'node:fs';
import { parseDocument } from 'yaml';
const brand = JSON.parse(readFileSync('branding/brand.json', 'utf8'));
const json = path => JSON.parse(readFileSync(path, 'utf8'));
for (const path of ['package.json', 'apps/desktop/package.json']) {
  const pkg = json(path);
  if (path.includes('desktop')) pkg.productName = brand.name;
  pkg.description = brand.description;
  pkg.homepage = brand.homepage;
  pkg.repository = { type: 'git', url: `${brand.homepage}.git` };
  writeFileSync(path, `${JSON.stringify(pkg, null, 2)}\n`);
}
const path = 'apps/desktop/electron-builder.yml';
const doc = parseDocument(readFileSync(path, 'utf8'));
doc.set('productName', brand.name);
doc.set('appId', brand.compatibility.appId);
const [owner, repo] = brand.repository.split('/');
doc.setIn(['publish', 'owner'], owner);
doc.setIn(['publish', 'repo'], repo);
writeFileSync(path, String(doc));
writeFileSync('apps/desktop/src/main/brand.ts', `// Generated by yarn brand:apply. Edit branding/brand.json instead.\nexport const BRAND = ${JSON.stringify(brand, null, 2)} as const;\n`);
let html = readFileSync('apps/desktop/src/renderer/index.html', 'utf8');
html = html.replace(/<title>.*?<\/title>/, `<title>${brand.name}</title>`);
writeFileSync('apps/desktop/src/renderer/index.html', html);
const manifestPath = 'apps/desktop/resources/companion/manifest.json';
const companion = json(manifestPath);
companion.name = `${brand.name} Companion`;
companion.description = `Add extensions to ${brand.name} from Chrome Web Store pages.`;
writeFileSync(manifestPath, `${JSON.stringify(companion, null, 2)}\n`);
console.log(`Applied ${brand.name} display identity; storage and protocol identifiers preserved.`);
