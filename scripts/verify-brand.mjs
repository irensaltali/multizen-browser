import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { parse } from 'yaml';
const read = path => readFileSync(path, 'utf8');
const brand = JSON.parse(read('branding/brand.json'));
assert.equal(JSON.parse(read('package.json')).version, JSON.parse(read('apps/desktop/package.json')).version);
const config = parse(read('apps/desktop/electron-builder.yml'));
assert.equal(config.productName, brand.name);
assert.equal(config.appId, 'com.multizen.desktop');
assert.equal(brand.compatibility.storageName, 'MultiZen');
assert.equal(brand.compatibility.ipcNamespace, 'multizen');
assert.equal(config.publish.owner + '/' + config.publish.repo, brand.repository);
assert.equal(JSON.parse(read('apps/desktop/package.json')).productName, brand.name);
assert.equal(read('apps/desktop/src/main/brand.ts'), `// Generated by yarn brand:apply. Edit branding/brand.json instead.\nexport const BRAND = ${JSON.stringify(brand, null, 2)} as const;\n`);
assert.equal(read('apps/desktop/src/renderer/public/brand-mark.svg'), read('branding/mark.svg'));
assert.equal(read('branding/mark.svg'), read(brand.logo.source), 'Application icon must match the selected logo');
const main = read('apps/desktop/src/main/index.ts');
assert.ok(main.indexOf('app.setName(BRAND.compatibility.storageName)') < main.indexOf('app.whenReady().then'));
assert.match(main, /join\(app.getPath\("appData"\), BRAND.compatibility.storageName\)/);
assert.match(main, /app.whenReady\(\).then\(async \(\) => \{\s*app.setName\(BRAND.name\)/);
assert.match(main, /gatewayService\?\.maybeSync\("focus"\)/);
assert.match(read('apps/desktop/src/renderer/src/App.tsx'), /sync.onProgress/);
assert.match(read('apps/desktop/src/main/mcp-gateway/agentAdapters.ts'), /managed by MultiZen, do not edit inside this block/);
assert.match(read('apps/desktop/src/main/UpdaterService.ts'), /irensaltali\/multizen-browser\/releases/);
function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) scan(path);
    else if (/\.(tsx|html)$/.test(path)) assert.ok(!/(MultiZen|Avenrail)/.test(read(path)), `Old display name returned: ${path}`);
  }
}
scan('apps/desktop/src/renderer');
for (const pkg of ['sync-core','kopia-adapter','s3-coordinator','mcp-gateway']) {
  assert.ok(JSON.parse(read('package.json')).scripts.test.includes(`@multizen/${pkg} test`), `${pkg} regression suite removed`);
}
console.log('Brand, update channel, storage compatibility and fork regression gates verified.');
